#!/usr/bin/env python3
"""Inventory the Fatmap asset bundle from the APK.

Extracts `assets/assets.zip` from an APK or XAPK and writes:
    data/fatmap-assets.txt   every entry, grouped
    spec/fatmap-styles.json   a summary of each map style

The map styles are the interesting part: they carry the tile, font and sprite
URLs the engine fetches at run time, including ones that appear nowhere in the
DEX.

Usage:
    python3 tools/inventory_assets.py com.strava.apk
"""

from __future__ import annotations

import argparse
import collections
import io
import json
import pathlib
import re
import sys
import zipfile


def find_assets_zip(apk: pathlib.Path) -> bytes | None:
    """Return the bytes of assets/assets.zip, looking inside an XAPK if needed."""
    with zipfile.ZipFile(apk) as outer:
        names = outer.namelist()
        if "assets/assets.zip" in names:
            return outer.read("assets/assets.zip")
        # An XAPK: the base APK holds the assets.
        for name in names:
            if not name.endswith(".apk"):
                continue
            with zipfile.ZipFile(io.BytesIO(outer.read(name))) as inner:
                if "assets/assets.zip" in inner.namelist():
                    return inner.read("assets/assets.zip")
    return None


def group_of(name: str) -> str:
    if name.startswith("Shared/Configs/GeneratedIcons/X1"):
        return "icons@1x"
    if name.startswith("Shared/Configs/GeneratedIcons/X2"):
        return "icons@2x"
    if name.startswith("Shared/Configs/") and name.endswith("style.json"):
        return "map styles"
    if name.startswith("Shared/Shaders/Terrain"):
        return "shader:terrain"
    if name.startswith("Shared/Shaders/"):
        return "shader:other"
    if name.startswith("RTShaderLib/"):
        return "shader:ogre-rt"
    if name.startswith("Main/"):
        return "ogre-main"
    if name.startswith("Shared/Textures/Heatmap"):
        return "texture:heatmap"
    if name.startswith("Shared/Textures/Terrain"):
        return "texture:terrain"
    if name.startswith("Shared/Textures"):
        return "texture:other"
    if name.startswith("Shared/VectorFonts"):
        return "font:ttf"
    if name.startswith("Shared/SDFonts"):
        return "font:sdf"
    if name.startswith("Shared/Skybox"):
        return "skybox"
    if name.startswith("Data/"):
        return "data"
    if name.startswith("lua/"):
        return "lua"
    if name.startswith("textures/"):
        return "texture:mobile"
    return "root"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("apk", help="the XAPK or APK to read")
    ap.add_argument("--data-out", default="data/fatmap-assets.txt")
    ap.add_argument("--spec-out", default="spec/fatmap-styles.json")
    args = ap.parse_args()

    raw = find_assets_zip(pathlib.Path(args.apk))
    if raw is None:
        print("no assets/assets.zip found", file=sys.stderr)
        return 1

    with zipfile.ZipFile(io.BytesIO(raw)) as z:
        names = z.namelist()
        groups = collections.defaultdict(list)
        for name in names:
            groups[group_of(name)].append(name)

        out = [
            "# Fatmap assets.zip inventory",
            "# Generated by tools/inventory_assets.py - do not edit by hand.",
            f"# entries: {len(names)}",
            "",
        ]
        for group in sorted(groups):
            out.append(f"## {group}  ({len(groups[group])})")
            out.extend(f"  {n}" for n in sorted(groups[group]))
            out.append("")
        pathlib.Path(args.data_out).write_text("\n".join(out))

        styles = {}
        for name in names:
            if not (name.endswith("style.json") and "/Configs/" in name):
                continue
            try:
                doc = json.loads(z.read(name))
            except (ValueError, KeyError):
                continue
            sources = doc.get("sources", {})
            kinds = collections.Counter(layer.get("type") for layer in doc.get("layers", []))
            styles[name.split("/Configs/")[1].split("/")[0]] = {
                "styleName": doc.get("name"),
                "styleVersion": doc.get("version"),
                "sources": len(sources),
                "layers": len(doc.get("layers", [])),
                "layerTypes": dict(kinds),
                "glyphs": doc.get("glyphs"),
                "sprite": doc.get("sprite"),
                "sourceUrls": sorted(
                    {v.get("url", "") for v in sources.values() if isinstance(v, dict)}
                ),
            }
        pathlib.Path(args.spec_out).write_text(json.dumps(styles, indent=1, sort_keys=True))

    print(f"entries       : {len(names)}")
    print(f"map styles    : {len(styles)}")
    print(f"wrote {args.data_out}")
    print(f"wrote {args.spec_out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
